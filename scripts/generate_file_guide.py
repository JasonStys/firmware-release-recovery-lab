"""File: Generate per-code-file responsibilities from actual authored opening comments.

main uses the same Git deliverable boundary as the original policy gate. Descriptions
are navigation summaries; exact declarations are in docs/code-index.md.
"""

import ast
import re
from pathlib import Path

from verify_repo import CODE_PREFIXES, public_files

ROOT = Path(__file__).resolve().parents[1]


def description(path: Path) -> str:
    """Extract only an authored opening purpose, without importing or executing source."""
    text = path.read_text(encoding="utf-8")
    if path.suffix == ".py":
        opening = (ast.get_docstring(ast.parse(text)) or "").split("\n\n")[0]
    else:
        lines = []
        for line in text.splitlines()[:8]:
            if line.startswith(("<!doctype", "#!/")):
                continue
            if not line.strip() or line.strip().startswith(
                ("//!", "/**", "/*", "*", "//", "<!--", "#")
            ):
                lines.append(
                    re.sub(r"^\s*(?://!|//|/\*\*?|\*|<!--|#)\s?", "", line)
                    .replace("*/", "")
                    .replace("-->", "")
                )
            else:
                break
        opening = " ".join(lines)
    opening = re.sub(r"^File:\s*", "", " ".join(opening.split()))
    opening = opening.split(" Lines:")[0].split(" Exact lines:")[0]
    if not opening:
        raise ValueError(f"Missing source responsibility: {path.relative_to(ROOT)}")
    return opening.replace("|", "\\|").replace("`", "")


def main():
    """Write one stable row per published/proposed code file, including browser/native tooling."""
    lines = [
        "# Source file guide",
        "",
        "Generated by `scripts/generate_file_guide.py` from authored file headers.",
        "The [repository map](repository-map.md) covers non-code files and historical reports.",
        "See the [code index](code-index.md) for exact declaration, parameter and variable lines.",
        "",
        "| File | Responsibility |",
        "| --- | --- |",
    ]
    for path in public_files():
        if path.suffix in CODE_PREFIXES:
            relative = path.relative_to(ROOT).as_posix()
            lines.append(f"| [{relative}](../{relative}) | {description(path)} |")
    (ROOT / "docs/source-file-guide.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
    )


if __name__ == "__main__":
    main()
